from diffusers import DiffusionPipeline
import torch


pipe = DiffusionPipeline.from_pretrained("stabilityai/stable-diffusion-xl-base-1.0", torch_dtype=torch.float16, use_safetensors=True, variant="fp16")
pipe.to("cuda")

prompt = """Generate an evocative visual representation of the [genre] song
by emphasizing its mood, tempo, and key elements.
Capture the essence of the music through vibrant colors, dynamic shapes,
and compelling imagery, translating the auditory experience into a visually engaging scene.
Consider the emotions conveyed by the song and aim to encapsulate its unique
atmosphere in a single, striking image.
"""

images = pipe(prompt=prompt).images[0]
images.save("image4.png")